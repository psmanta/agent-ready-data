#!/usr/bin/env python3
"""
Amendment-versus-code consistency check -- Experiment 1b pre-registration
=========================================================================
The Agentic Data Contract . Pillar 1: Authoritative

A pre-registration is worth little if the document and the code that runs it disagree. This script
verifies every number, pattern list, constant and table in 1b_DESIGN_AMENDMENT_1.md that is also defined
in code, and exits 1 on any disagreement. It also lints the keyword list (an unparenthesized `|` once
let a pattern match inside "unquestionably") and refuses known stale phrases.

    python check_amendment_consistency.py                  # from 1b_dithering/
    python check_amendment_consistency.py --selftest       # corrupts the text 23 ways; each must be caught
    python check_amendment_consistency.py --skip_artifact_files   # when not run inside the repo layout

Checks
  keyword list    the amendment's 25 patterns equal H5_KEYWORD_PATTERNS, in order; none has top-level alternation;
                  behaviour tests (positives and negatives, including "unquestionably")
  conditions      the amendment's per-hypothesis counts and total equal the engine's build_all_conditions()
  costs           the stated dollar ranges follow from the stated call counts at $0.00232 per record
  H1 rule         1a's top 5, the six legacy comparison fields, the twelve reused fields, the trigger, the
                  bootstrap constants and the seed block equal h1_baseline_replication.py and the engine
  judge, echo     PROMPT_ID and model; the echo factor list
  redundancy      the H4 table equals the table generated by field_redundancy.py; stated ranges
  freeze          the artifact lists equal freeze_manifest.ARTIFACTS (and exist, unless skipped)
  stale phrases   none of the known stale statements remain
"""
import argparse
import re
import sys
from pathlib import Path
from typing import Callable, List, Tuple

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent.parent / "shared" / "data_generation"))
sys.path.insert(0, str(HERE))

AMENDMENT = HERE / "1b_DESIGN_AMENDMENT_1.md"
PER_RECORD_COST = 0.00232
STALE_PHRASES = ["46–47", "46-47", "17 patterns", "business_decision_agent_1b.py", "H4 reduced from 6 to 3",
                 "minimum of 25 (exact number pending", "8 → 11 conditions", "55-56**", "$62–64"]

# (text, should the 25-pattern scanner flag it?)
KEYWORD_BEHAVIOUR = [
    ("This is an unquestionably high-value customer.", False), ("He is unquestionably loyal.", False),
    ("A questionableness of tone.", False), ("The value looks questionable.", True),
    ("The value is questionably high.", True), ("This value is unusually high.", True),
    ("The score is oddly low.", True), ("The tenure is suspiciously long.", True),
    ("an anomalously large spend", True), ("surprisingly, the score is low", True),
    ("There is a data quality issue here.", True), ("Customer is a great fit with strong engagement.", False),
    ("the odds of churn are low", False),
]


def section(text: str, title: str) -> str:
    a = text.index("## " + title)
    b = text.find("\n## ", a + 5)
    return text[a:(len(text) if b == -1 else b)]


def sub_section(block: str, heading: str) -> str:
    a = block.index(heading)
    b = block.find("\n### ", a + 5)
    return block[a:(len(block) if b == -1 else b)]


def top_level_alternation(pattern: str) -> bool:
    depth, i = 0, 0
    while i < len(pattern):
        c = pattern[i]
        if c == "\\":
            i += 2; continue
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        elif c == "|" and depth == 0:
            return True
        i += 1
    return False


def run_checks(text: str, skip_files: bool, base_dir: Path = HERE) -> List[Tuple[str, bool, str]]:
    import evaluate_core as ec
    import field_redundancy as fr
    import freeze_manifest as fm
    import h1_baseline_replication as H
    import classifier_prompt as cp
    from dither_engine import build_all_conditions
    from collections import Counter

    results: List[Tuple[str, bool, str]] = []
    def check(name: str, ok: bool, detail: str = "") -> None:
        results.append((name, bool(ok), detail))

    # ---- keyword list -------------------------------------------------------------------------
    h5 = section(text, "H5 — Detection Awareness (Fully Specified)")
    kw = sub_section(h5, "### The frozen keyword list")
    kw = kw[:kw.index('**"Uncertain about" considered')]
    in_text = [l for l in kw.splitlines() if l.startswith("\\b")]
    check("keyword list: the amendment's patterns equal H5_KEYWORD_PATTERNS, in order", in_text == list(ec.H5_KEYWORD_PATTERNS),
          f"amendment has {len(in_text)}, code has {len(ec.H5_KEYWORD_PATTERNS)}; first difference: " +
          next((f"{a!r} vs {b!r}" for a, b in zip(in_text, ec.H5_KEYWORD_PATTERNS) if a != b), "length"))
    check("keyword list: exactly 25 patterns and the heading says 25", len(ec.H5_KEYWORD_PATTERNS) == 25 and "(final, 25 patterns)" in kw)
    bad = [p for p in ec.H5_KEYWORD_PATTERNS if top_level_alternation(p)]
    check("keyword list: no pattern has top-level alternation (it would escape its word boundaries)", not bad, f"offenders: {bad}")
    wrong = [(s, want) for s, want in KEYWORD_BEHAVIOUR if ec.detect_h5_keywords(s)["detected"] != want]
    check("keyword list: behaviour tests pass (positives flagged, negatives such as 'unquestionably' not)", not wrong, f"wrong: {wrong}")

    # ---- conditions ----------------------------------------------------------------------------
    counts = Counter(c.condition_id.split("_")[0] for c in build_all_conditions())
    cost = section(text, "Updated Condition Count and Cost Implications")
    rows = dict(re.findall(r"\|\s*(H\d+[ab]?)(?:\s*\(new\))?\s*\|[^|]*\|\s*(\d+|0–1)", cost))
    expect = {"H1": counts["h1"], "H2": counts["h2"], "H3": counts["h3"], "H4": counts["h4"], "H7": counts["h7"], "H8a": counts["h8a"]}
    check("conditions: the amendment's per-hypothesis counts equal the engine's", all(rows.get(k) == str(v) for k, v in expect.items()),
          f"amendment {rows} vs engine {expect}")
    total = sum(counts.values())
    check("conditions: total equals the engine's (and the text says so)", total == 55 and f"**{total} (up to" in cost, f"engine total {total}")

    # ---- costs ---------------------------------------------------------------------------------
    lo, hi, hi2 = (round(n * PER_RECORD_COST) for n in (61_000, 62_000, 67_000))
    blo, bhi, bhi2 = (round(n * PER_RECORD_COST / 2) for n in (61_000, 62_000, 67_000))
    check("costs: standard-price ranges follow from the call counts", f"${lo}–{hi}" in cost and f"${hi2} standard" in cost, f"expected ${lo}–{hi} and ${hi2}")
    check("costs: Batch-price ranges follow from the call counts", f"${blo}–{bhi}" in cost and f"${bhi2} Batch" in cost, f"expected ${blo}–{bhi} and ${bhi2}")
    check("costs: the H1 conditional adds at most 5,000 calls (about $12)", "5,000 calls (about $12" in cost and round(5000 * PER_RECORD_COST) == 12)

    # ---- H1 rule -------------------------------------------------------------------------------
    h1 = sub_section(section(text, "H1 — Field Importance Validation (Restructured)"), "### Conditional replication rule")
    existing = sorted(H.existing_individual_fields())
    names_in = lambda m: re.findall(r"`([^`]+)`", m.group(1)) if m else None
    top5 = names_in(re.search(r"top 5 \(its H4\): (.*?)\. 1a measured", h1, re.S))
    check("H1 rule: the sentence naming 1a's top 5 lists exactly A1A_TOP5, in order", top5 == list(H.A1A_TOP5), f"parsed {top5}")
    six = names_in(re.search(r"comparison = exactly the six fixed above \((.*?)\)", h1))
    check("H1 rule: the legacy comparison sentence lists exactly LEGACY_COMPARISON, in order", six == list(H.LEGACY_COMPARISON), f"parsed {six}")
    reused = names_in(re.search(r"are reused: (.*?)\. Up to five new conditions", h1, re.S))
    check("H1 rule: the reused-fields sentence lists exactly the engine's twelve existing individual conditions",
          len(existing) == 12 and reused is not None and sorted(reused) == existing, f"parsed {reused}; engine {existing}")
    check("H1 rule: trigger threshold, bootstrap constants and seed block match the code",
          H.TRIGGER_MAX_OVERLAP == 2 and "overlap of 0, 1 or 2" in h1 and f"B = {H.BOOTSTRAP_B}" in h1 and str(H.BOOTSTRAP_SEED) in h1 and "seeds 500-524" in h1)
    check("H1 rule: the seed block fits the field count (25 fields -> 500-524)", len(fr.DITHERED_FIELDS) == 25)

    # ---- judge, echo ---------------------------------------------------------------------------
    check("judge: PROMPT_ID in the amendment equals classifier_prompt.PROMPT_ID", f"PROMPT_ID {cp.PROMPT_ID}" in h5 and cp.PROMPT_ID == "v3-be665399de", cp.PROMPT_ID)
    check("H5: the evaluator's definitions are stated (behavior changed incl. confidence; inertia needs three texts; completeness refusal)",
          "### Definitions the evaluator fixes" in h5 and "OR the dithered confidence lies outside" in h5 and "at least three matching baseline texts" in h5 and "--allow_incomplete" in h5 and "Perturbed means changed" in h5 and "Class-by-drift matrices" in h5 and "Audit stamp" in h5)
    repro = section(text, "A Note on Data Generation Reproducibility")
    check("data: the synthetic-realism paragraph is stated (example.com replaced by realistic consumer emails; coincidence; no outreach)",
          "**Synthetic realism.**" in repro and "example.com" in repro and "coincidence" in repro and "no address is ever used for outreach" in repro)
    coll = section(text, "Collection Design: Windows, Controls and Fingerprints")
    check("collection: the design states its finding, the randomized block, the control, the fingerprint and the guarantees",
          all(x in coll for x in ("3 of 30", "randomized complete block", "five different blocks", "h0_clean_rerun_1", "control.json", "adds 1,000 calls", ".meta.jsonl", "writes nothing for a condition that is incomplete", "does not remove window effects")))
    check("judge: model and temperature stated", "claude-haiku-4-5-20251001" in h5 and "temperature 0" in h5)
    check("judge: the decided scope is the eight H4 conditions, and the engine has exactly eight H4 conditions",
          "Judged scope (decided): the eight H4 conditions" in h5 and counts["h4"] == 8, f"engine H4 count {counts['h4']}")
    names = ", ".join(n for n, _ in ec.ECHO_SCALE_FACTORS)
    check("echo: the frozen confirmatory factor list equals ECHO_SCALE_FACTORS", f"x100, /100, /12, x12" in h5 and names == "x100, /100, /12, x12", names)

    # ---- redundancy ----------------------------------------------------------------------------
    h4 = section(text, "H4 — Dither Type Effects (Restructured)")
    head = "| Field | Strict | Bounded | Approximate | Soft (segment band) | Engine recomputes | Class (default) | Class (isolated arm) | Range stated to agent |"
    gen = []
    for f in fr.DITHERED_FIELDS:
        p, q = fr.redundancy_profile(f), fr.redundancy_profile(f, recompute_derived=False)
        s = p["siblings"]
        rng = "{:g}-{:g}".format(*p["stated_range"]) if p["stated_range"] else "-"
        gen.append(f"| `{f}` | {', '.join(s.get('strict', [])) or '-'} | {', '.join(s.get('bounded', [])) or '-'} | "
                   f"{', '.join(s.get('approximate', [])) or '-'} | {'segment' if 'soft' in s else '-'} | {', '.join(p['propagated']) or '-'} | {p['class']} | {q['class']} | {rng} |")
    check("redundancy: the amendment's table equals the table field_redundancy.py generates", head in h4 and all(r in h4 for r in gen) and len(gen) == 25,
          next((r for r in gen if r not in h4), ""))
    check("redundancy: every stated-range field is named in the text", all(f"`{f}`" in h4 for f in fr.STATED_RANGES))

    # ---- freeze --------------------------------------------------------------------------------
    fz = section(text, "Pre-Registration Freeze")
    for stage, marker, nxt in (("collection", "**Collection stage**", "**Analysis stage**"), ("analysis", "**Analysis stage**", "**Deliberately not frozen")):
        block = fz[fz.index(marker):fz.index(nxt)]
        # repo-root paths in the amendment ("shared/...", "requirements.txt") are relative to 1b_dithering in the manifest
        listed = [("../../../" + m) if (m.startswith("shared/") or m == "requirements.txt") else m
                  for m in re.findall(r"- `([^`]+)`", block)]
        check(f"freeze: the amendment's {stage} list equals freeze_manifest.ARTIFACTS", listed == fm.ARTIFACTS[stage], f"{len(listed)} vs {len(fm.ARTIFACTS[stage])}")
        if stage == "collection" and not skip_files:
            missing = [p for p in fm.ARTIFACTS[stage] if not (base_dir / p).exists()]
            check("freeze: every collection-stage artifact exists", not missing, f"missing: {missing}")

    check("freeze: the commitment that makes the two stages valid is stated",
          "No result from any dithered condition is examined until `freeze_manifest.py write --stage analysis`" in fz)

    # ---- stale phrases -------------------------------------------------------------------------
    present = [p for p in STALE_PHRASES if p in text]
    check("no known stale statement remains", not present, f"found: {present}")
    return results


def selftest(text: str) -> int:
    """Corrupt the amendment in memory; every corruption must fail at least one check."""
    base_failures = {n for n, ok, _ in run_checks(text, True) if not ok}
    if base_failures:
        print("❌ selftest needs a passing baseline; failing:", sorted(base_failures)); return 1
    mutations: List[Tuple[str, Callable[[str], str]]] = [
        ("a keyword pattern edited", lambda s: s.replace("\\bunusual(?:ly)?\\b", "\\bunusual\\b", 1)),
        ("the precedence bug reintroduced", lambda s: s.replace("\n\\bquestionabl(?:e|y)\\b\n", "\n\\bquestionable|questionably\\b\n", 1)),
        ("a keyword pattern deleted", lambda s: s.replace("\\bdata problem\\b\n", "", 1)),
        ("a condition count changed", lambda s: s.replace("| H3 | 8 | 15 |", "| H3 | 8 | 14 |", 1)),
        ("the total changed", lambda s: s.replace("**55 (up to 61 with both conditionals)**", "**56 (up to 61 with both conditionals)**", 1)),
        ("a cost range changed", lambda s: s.replace("$142–144", "$130–144", 1)),
        ("the randomized-block design removed", lambda s: s.replace("randomized complete block", "sequential run", 1)),
        ("the baseline-runs-across-windows guarantee reworded", lambda s: s.replace("five different blocks", "one block", 1)),
        ("the judge prompt id changed", lambda s: s.replace("PROMPT_ID v3-be665399de", "PROMPT_ID v3-00000000aa", 1)),
        ("a legacy comparison field dropped from the rule", lambda s: s.replace("`tenure_months`, `avg_resolution_time_hours`, `refund_rate`)", "`tenure_months`, `refund_rate`)", 1)),
        ("a field dropped from 1a's list in the rule", lambda s: s.replace("`nps_score`, `lifetime_value_estimate` and `support_tickets_open`.", "`nps_score` and `support_tickets_open`.", 1)),
        ("a reused field dropped from the rule", lambda s: s.replace("`avg_resolution_time_hours`, `refund_rate` and `payment_failures` (H3)", "`avg_resolution_time_hours` and `refund_rate` (H3)", 1)),
        ("the trigger threshold reworded", lambda s: s.replace("overlap of 0, 1 or 2", "overlap of 0, 1, 2 or 3", 1)),
        ("a redundancy table row edited", lambda s: s.replace("| soft_only | strict |", "| soft_only | none |", 1)),
        ("an artifact removed from the freeze list", lambda s: s.replace("- `evaluate_h4.py`\n", "", 1)),
        ("the inertia text-count rule reworded", lambda s: s.replace("at least three matching baseline texts", "at least two matching baseline texts", 1)),
        ("the confidence part of 'behavior changed' removed", lambda s: s.replace("OR the dithered confidence lies outside", "and nothing else lies outside", 1)),
        ("the 'perturbed means changed' guarantee removed", lambda s: s.replace("Perturbed means changed", "Perturbed means selected", 1)),
        ("the audit stamp paragraph removed", lambda s: s.replace("**Audit stamp.**", "**Provenance.**", 1)),
        ("the synthetic-realism paragraph removed", lambda s: s.replace("**Synthetic realism.**", "**Notes.**", 1)),
        ("the judged scope reworded", lambda s: s.replace("Judged scope (decided): the eight H4 conditions", "Judged scope (decided): every dithered condition", 1)),
        ("the two-stage commitment removed", lambda s: s.replace("No result from any dithered condition is examined until", "Results may be examined before", 1)),
        ("a stale statement reintroduced", lambda s: s.replace("### Revision 2", "- Total condition count increased from 21 to 46–47\n\n### Revision 2", 1)),
    ]
    caught = 0
    for label, fn in mutations:
        mutated = fn(text)
        if mutated == text:
            print(f"  ⚠️  mutation did not apply: {label}"); continue
        failed = [n for n, ok, _ in run_checks(mutated, True) if not ok]
        print(f"  {'✅' if failed else '❌'} {label}: {'caught by ' + str(len(failed)) + ' check(s)' if failed else 'NOT CAUGHT'}")
        caught += bool(failed)
    print(f"\n{caught} of {len(mutations)} corruptions caught")
    return 0 if caught == len(mutations) else 1


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--amendment", type=Path, default=AMENDMENT)
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--skip_artifact_files", action="store_true")
    a = ap.parse_args()
    text = a.amendment.read_text()
    if a.selftest:
        return selftest(text)
    results = run_checks(text, a.skip_artifact_files)
    for name, ok, detail in results:
        print(f"  {'✅' if ok else '❌'} {name}" + (f"\n       {detail}" if not ok and detail else ""))
    bad = [r for r in results if not r[1]]
    print(f"\n{len(results) - len(bad)} of {len(results)} checks passed" + ("" if not bad else f"; {len(bad)} FAILED"))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
